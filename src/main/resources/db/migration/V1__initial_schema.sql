CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(255) NOT NULL UNIQUE, password_hash VARCHAR(255),
 first_name VARCHAR(100) NOT NULL, last_name VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL, picture TEXT, email_verified BOOLEAN NOT NULL,
 is_active BOOLEAN NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE email_tokens (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id), token VARCHAR(512) NOT NULL UNIQUE,
 type VARCHAR(50) NOT NULL, expires_at TIMESTAMP WITH TIME ZONE NOT NULL, used BOOLEAN NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_email_tokens_user_id ON email_tokens(user_id);
CREATE TABLE conversions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT REFERENCES users(id),
 session_id VARCHAR(255), converter_type VARCHAR(100) NOT NULL,
 original_file_name VARCHAR(500), converted_file_name VARCHAR(500), file_id VARCHAR(255),
 file_size BIGINT, created_at TIMESTAMP WITH TIME ZONE NOT NULL, expires_at TIMESTAMP WITH TIME ZONE NOT NULL, ip_address VARCHAR(45)
);
CREATE INDEX idx_conversions_user_id ON conversions(user_id);
CREATE INDEX idx_conversions_session_id ON conversions(session_id);
CREATE INDEX idx_conversions_file_id ON conversions(file_id);
CREATE INDEX idx_conversions_expires_at ON conversions(expires_at);
CREATE TABLE analytics (id BIGINT PRIMARY KEY, total_visits BIGINT, unique_visitors BIGINT, total_conversions BIGINT, updated_at TIMESTAMP WITH TIME ZONE);
CREATE TABLE tool_stats (tool VARCHAR(100) PRIMARY KEY, count BIGINT NOT NULL);
